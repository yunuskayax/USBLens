export function errorText(lang: Lang, raw: unknown): string {
  const t = dict[lang];
  const msg = String(raw ?? "");
  if (msg === "ADMIN_REQUIRED") return t.adminRequired;
  if (msg === "NOT_FOUND") return t.notFound;
  if (msg === "WINDOWS_ONLY") return t.windowsOnly;
  if (msg.startsWith("UPDATE_FAILED")) return t.updateFailed;
  if (msg === "UPDATE_HASH_MISMATCH" || msg === "UPDATE_BAD_FILE")
    return lang === "tr" ? "İndirilen dosya doğrulanamadı, güvenlik için kurulmadı. Tekrar deneyin." : "The downloaded file could not be verified and was not installed. Please try again.";
  if (msg === "UPDATE_URL_REJECTED") return lang === "tr" ? "Güncelleme bağlantısı güvenilir değil." : "The update link is not trusted.";
  if (msg.startsWith("VETOED:")) {
    const who = msg.slice(7).trim();
    return who ? `${t.vetoed} (${who})` : t.vetoed;
  }
  return msg;
}

/** Human text for a security reason code from the Rust side. */
export function reasonText(lang: Lang, code: string): string {
  const [head, arg = ""] = code.split(/:(.*)/s);
  const tr = lang === "tr";
  switch (head) {
    case "KEYBOARD_AND_STORAGE":
      return tr ? "Hem klavye hem depolama gibi davranıyor — BadUSB saldırı cihazı olabilir" : "Acts as both a keyboard and storage — possible BadUSB attack device";
    case "PROGRAMMABLE_BOARD":
      return tr ? `Programlanabilir kart (${arg}) — klavye taklidi yapacak şekilde programlanabilir` : `Programmable board (${arg}) — can be programmed to act as a keyboard`;
    case "NEW_KEYBOARD":
      return tr ? "Bu bilgisayara ilk kez takılan bir klavye" : "A keyboard connected to this PC for the first time";
    case "NOT_ALLOWED":
      return tr ? "Beyaz listede olmayan cihaz" : "Device is not on the allowlist";
    default:
      return code;
  }
}
